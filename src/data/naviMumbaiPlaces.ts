function extractArea(name: string): string {
  const lower = name.toLowerCase();
  const areas: Array<[string, string]> = [
    ['seawoods', 'Seawoods'], ['vashi', 'Vashi'], ['kharghar', 'Kharghar'],
    ['nerul', 'Nerul'], ['sanpada', 'Sanpada'], ['kopar khairane', 'Kopar Khairane'],
    ['juinagar', 'Juinagar'], ['belapur', 'CBD Belapur'], ['panvel', 'Panvel'],
    ['ghatkopar', 'Ghatkopar'], ['kurla', 'Kurla'], ['lower parel', 'Lower Parel'],
    ['bandra', 'Bandra'], ['juhu', 'Juhu'], ['andheri', 'Andheri'], ['versova', 'Versova'],
    ['malad', 'Malad'], ['goregaon', 'Goregaon'], ['kandivali', 'Kandivali'],
    ['borivali', 'Borivali'], ['santacruz', 'Santacruz'], ['dadar', 'Dadar'],
    ['worli', 'Worli'], ['bkc', 'BKC'], ['colaba', 'Colaba'], ['fort', 'Fort'],
    ['churchgate', 'Churchgate'], ['marine lines', 'Marine Lines'], ['tardeo', 'Tardeo'],
    ['haji ali', 'Haji Ali'], ['mumbai central', 'Mumbai Central'], ['chembur', 'Chembur'],
    ['powai', 'Powai'], ['ghansoli', 'Ghansoli'], ['airoli', 'Airoli'], ['belapur', 'CBD Belapur'], ['turbhe', 'Turbhe'], ['bhandup', 'Bhandup'], ['mulund', 'Mulund'], ['mira road', 'Mira Road'],
  ];
  for (const [needle, area] of areas) {
    if (lower.includes(needle)) return area;
  }
  return 'Mumbai';
}

